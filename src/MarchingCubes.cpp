// Edge-vertex weld key: pack the two grid-corner indices the edge crosses (the
// lower one first) into a 64-bit key. Two cubes sharing that edge interpolate the
// identical vertex, so hashing on this key welds them into one index.
inline uint64_t edgeKey(uint64_t cornerA, uint64_t cornerB)
{
    return (cornerA < cornerB) ? (cornerA << 32 | cornerB)
                               : (cornerB << 32 | cornerA);
}

