Mesh extract(const float* field, int nx, int ny, int nz,
             float isoLevel,
             const std::array<float, 3>& gridMin,
             const std::array<float, 3>& gridMax)
{
    Mesh out;
    if (!field || nx < 2 || ny < 2 || nz < 2)
        return out;

    const size_t sliceStride = static_cast<size_t>(nx) * ny;
    auto idx = [nx, sliceStride](int x, int y, int z) -> size_t {
        return static_cast<size_t>(z) * sliceStride
             + static_cast<size_t>(y) * nx + x;
    };
    // Map an integer grid corner to world space.
    auto denom = [](int n) { return (n > 1) ? float(n - 1) : 1.0f; };
    const float sx = (gridMax[0] - gridMin[0]) / denom(nx);
    const float sy = (gridMax[1] - gridMin[1]) / denom(ny);
    const float sz = (gridMax[2] - gridMin[2]) / denom(nz);
    auto worldOf = [&](float x, float y, float z, float out3[3]) {
        out3[0] = gridMin[0] + x * sx;
        out3[1] = gridMin[1] + y * sy;
        out3[2] = gridMin[2] + z * sz;
    };

    // A stable index per grid corner (x + y*nx + z*nx*ny), used as the vertex
    // weld key's building block.
    auto cornerId = [nx, sliceStride](int x, int y, int z) -> uint64_t {
        return static_cast<uint64_t>(z) * sliceStride
             + static_cast<uint64_t>(y) * nx + x;
    };

    std::unordered_map<uint64_t, uint32_t> vertexForEdge;
    vertexForEdge.reserve(static_cast<size_t>(nx) * ny * 2);

    // Interpolate the crossing vertex on one cube edge; weld via edgeKey.
    auto edgeVertex = [&](int cx, int cy, int cz, int edge) -> uint32_t {
        const int a = kEdgeCorners[edge][0];
        const int b = kEdgeCorners[edge][1];
        const int ax = cx + kCornerOffset[a][0], ay = cy + kCornerOffset[a][1], az = cz + kCornerOffset[a][2];
        const int bx = cx + kCornerOffset[b][0], by = cy + kCornerOffset[b][1], bz = cz + kCornerOffset[b][2];
        const uint64_t key = edgeKey(cornerId(ax, ay, az), cornerId(bx, by, bz));
        auto it = vertexForEdge.find(key);
        if (it != vertexForEdge.end())
            return it->second;

        const float va = field[idx(ax, ay, az)];
        const float vb = field[idx(bx, by, bz)];
        float t = 0.5f;
        const float d = vb - va;
        if (std::fabs(d) > 1e-12f)
            t = (isoLevel - va) / d;
        if (t < 0.0f) t = 0.0f;
        if (t > 1.0f) t = 1.0f;

        float pa[3], pb[3];
        worldOf(float(ax), float(ay), float(az), pa);
        worldOf(float(bx), float(by), float(bz), pb);
        const uint32_t vid = static_cast<uint32_t>(out.positions.size() / 3);
        out.positions.push_back(pa[0] + t * (pb[0] - pa[0]));
        out.positions.push_back(pa[1] + t * (pb[1] - pa[1]));
        out.positions.push_back(pa[2] + t * (pb[2] - pa[2]));
        vertexForEdge.emplace(key, vid);
        return vid;
    };

    // A corner is "inside" when its field value is >= isoLevel (inside-positive).
    for (int z = 0; z < nz - 1; ++z) {
        for (int y = 0; y < ny - 1; ++y) {
            for (int x = 0; x < nx - 1; ++x) {
                int cubeIndex = 0;
                for (int c = 0; c < 8; ++c) {
                    const float v = field[idx(x + kCornerOffset[c][0],
                                              y + kCornerOffset[c][1],
                                              z + kCornerOffset[c][2])];
                    if (v >= isoLevel)
                        cubeIndex |= (1 << c);
                }
                const int edges = kEdgeTable[cubeIndex];
                if (edges == 0)
                    continue;

                const int* tri = kTriTable[cubeIndex];
                for (int i = 0; tri[i] != -1; i += 3) {
                    const uint32_t v0 = edgeVertex(x, y, z, tri[i + 0]);
                    const uint32_t v1 = edgeVertex(x, y, z, tri[i + 1]);
                    const uint32_t v2 = edgeVertex(x, y, z, tri[i + 2]);
                    // Skip degenerate triangles (can occur when two edge
                    // vertices coincide at a grid corner exactly on the iso).
                    if (v0 == v1 || v1 == v2 || v0 == v2)
                        continue;
                    out.indices.push_back(v0);
                    out.indices.push_back(v1);
                    out.indices.push_back(v2);
                }
            }
        }
    }

    out.vertexCount   = static_cast<int>(out.positions.size() / 3);
    out.triangleCount = static_cast<int>(out.indices.size() / 3);
    return out;
}

