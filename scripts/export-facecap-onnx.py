def extract_task(task_path, dest):
    os.makedirs(dest, exist_ok=True)
    with zipfile.ZipFile(task_path) as z:
        z.extractall(dest)
    return {os.path.splitext(n)[0]: os.path.join(dest, n)
            for n in os.listdir(dest) if n.endswith(".tflite")}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--face-task", help="face_landmarker.task path")
    ap.add_argument("--pose-task", help="pose_landmarker_full.task path")
    ap.add_argument("--images", required=True,
                    help="dir with test images (face parity uses images whose "
                         "name doesn't start with 'pose', pose parity the rest)")
    ap.add_argument("--out-dir", default=".mocap_work/out")
    ap.add_argument("--canonical-obj", default=".mocap_work/canonical_face_model.obj")
    ap.add_argument("--procrustes", default=".mocap_work/geometry_pipeline_metadata_landmarks.pbtxt")
    ap.add_argument("--verify-only", action="store_true",
                    help="skip conversion, only run parity on existing out-dir")
    args = ap.parse_args()

    imgs = sorted(os.path.join(args.images, f) for f in os.listdir(args.images)
                  if f.lower().endswith((".jpg", ".jpeg", ".png")))
    face_imgs = [p for p in imgs if not os.path.basename(p).startswith("pose")]
    pose_imgs = [p for p in imgs if os.path.basename(p).startswith("pose")]

    report = {}
    if args.face_task:
        face_out = os.path.join(args.out_dir, "face")
        os.makedirs(face_out, exist_ok=True)
        if not args.verify_only:
            print("== converting face models ==")
            tflites = extract_task(args.face_task, os.path.join(args.out_dir, "_face_tflite"))
            convert_with_fallback(tflites["face_detector"],
                                  os.path.join(face_out, "face_detector.onnx"))
            convert_with_fallback(tflites["face_landmarks_detector"],
                                  os.path.join(face_out, "face_landmarks.onnx"))
            convert_with_fallback(tflites["face_blendshapes"],
                                  os.path.join(face_out, "face_blendshapes.onnx"))
        report["face"] = run_face_parity(args.face_task, args.out_dir, face_imgs,
                                         args.canonical_obj, args.procrustes)
        assert report["face"]["worst_blendshape_abs"] <= 0.02, "blendshape parity FAILED"
        # The documented contract advertises a 2px landmark target; enforce it
        # so parity can't silently regress while the script prints success.
        assert report["face"]["worst_landmark_px"] <= 2.0, (
            f"landmark parity FAILED "
            f"({report['face']['worst_landmark_px']:.2f}px > 2px)")

    if args.pose_task:
        pose_out = os.path.join(args.out_dir, "pose")
        os.makedirs(pose_out, exist_ok=True)
        if not args.verify_only:
            print("== converting pose models ==")
            tflites = extract_task(args.pose_task, os.path.join(args.out_dir, "_pose_tflite"))
            convert_with_fallback(tflites["pose_detector"],
                                  os.path.join(pose_out, "pose_detector.onnx"))
            convert_with_fallback(tflites["pose_landmarks_detector"],
                                  os.path.join(pose_out, "pose_landmarks.onnx"))
        report["pose"] = run_pose_parity(args.pose_task, args.out_dir, pose_imgs)
        assert report["pose"]["worst_world_m"] <= 0.02, "pose world parity FAILED"

    # contract dump for the C++ side / spike doc
    contract = {
        "blendshape_names": BLENDSHAPE_NAMES,
        "blendshape_landmark_subset": BLENDSHAPE_LANDMARK_SUBSET,
        "pose_landmark_names": POSE_LANDMARK_NAMES,
        "face_detector": {"input": 128, "range": [-1, 1],
                          "anchors": {"strides": [8, 16, 16, 16], "count": 896},
                          "keypoints": ["right_eye", "left_eye", "nose", "mouth",
                                        "right_ear", "left_ear"],
                          "roi": {"rotation_kp": [0, 1], "target_angle_deg": 0,
                                  "scale": 1.5, "square_long": True}},
        "face_landmarks": {"input": 256, "range": [0, 1],
                           "outputs": "1434=478*xyz in 256-space; presence logit"},
        "face_blendshapes": {"input": "[1,146,2] (x*W, y*H) px", "output": 52},
        "pose_detector": {"input": 224, "range": [-1, 1],
                          "anchors": {"strides": [8, 16, 32, 32, 32], "count": 2254},
                          "roi": {"center_kp": 0, "radius_kp": 1,
                                  "target_angle_deg": 90, "scale": 1.25}},
        "pose_landmarks": {"input": 256, "range": [0, 1],
                           "outputs": "195=39*(x,y,z,vis,presence); world 117=39*xyz metres"},
        "parity": report,
    }
    os.makedirs(args.out_dir, exist_ok=True)
    with open(os.path.join(args.out_dir, "mocap_contract.json"), "w") as f:
        json.dump(contract, f, indent=2)
    print(f"\ncontract + parity report -> {os.path.join(args.out_dir, 'mocap_contract.json')}")
    print("ALL PARITY CHECKS PASSED")


if __name__ == "__main__":
    sys.exit(main())
