def run_face_parity(face_task, out_dir, images, canonical_obj, procrustes_pbtxt):
    import mediapipe as mp
    from mediapipe.tasks import python as mp_python
    from mediapipe.tasks.python import vision as mp_vision
    from PIL import Image

    ours = OnnxFacePipeline(out_dir, canonical_obj, procrustes_pbtxt)
    options = mp_vision.FaceLandmarkerOptions(
        base_options=mp_python.BaseOptions(model_asset_path=face_task),
        output_face_blendshapes=True,
        output_facial_transformation_matrixes=True,
        num_faces=1)
    ref = mp_vision.FaceLandmarker.create_from_options(options)

    print("\n== FACE PARITY (ONNX pipeline vs python mediapipe) ==")
    worst_bs, worst_px, worst_deg = 0.0, 0.0, 0.0
    n_ok = 0
    n_mismatch = 0
    for path in images:
        img = Image.open(path)
        mp_img = mp.Image(image_format=mp.ImageFormat.SRGB,
                          data=np.asarray(img.convert("RGB")))
        res = ref.detect(mp_img)
        mine = ours(img)
        # Detection DISAGREEMENTS are parity failures, not skips: if we only
        # require n_ok > 0, one matching image can hide mismatches on every
        # other asset. Count them and assert none remain at the end.
        if not res.face_landmarks:
            if mine is not None:
                print(f"  {os.path.basename(path)}: MISMATCH — reference found "
                      f"no face, we did")
                n_mismatch += 1
            else:
                print(f"  {os.path.basename(path)}: no face (both agree)")
            continue
        if mine is None:
            print(f"  {os.path.basename(path)}: MISMATCH — reference found a "
                  f"face, we did NOT")
            n_mismatch += 1
            continue
        W, H = img.size
        ref_pts = np.array([[pt.x * W, pt.y * H] for pt in res.face_landmarks[0]])
        d_px = np.linalg.norm(ref_pts - mine["landmarks"][:, :2], axis=1)
        ref_bs = np.array([b.score for b in res.face_blendshapes[0]])
        d_bs = np.abs(ref_bs - mine["blendshapes"])
        deg = np.nan
        if res.facial_transformation_matrixes:
            Rref = np.array(res.facial_transformation_matrixes[0])[:3, :3]
            # our R maps canonical -> camera, so compare directly
            dR = Rref.T @ mine["rotation"]
            deg = math.degrees(math.acos(np.clip((np.trace(dR) - 1) / 2, -1, 1)))
        print(f"  {os.path.basename(path)}: landmarks mean {d_px.mean():.2f}px "
              f"max {d_px.max():.2f}px | blendshapes mean {d_bs.mean():.4f} "
              f"max {d_bs.max():.4f} | head-pose delta {deg:.2f} deg "
              f"| presence {mine['presence']:.3f}")
        worst_bs = max(worst_bs, d_bs.max())
        worst_px = max(worst_px, d_px.max())
        if not math.isnan(deg):
            worst_deg = max(worst_deg, deg)
        n_ok += 1
    ref.close()
    assert n_ok > 0, "no face image produced a reference result"
    assert n_mismatch == 0, (
        f"{n_mismatch} image(s) disagreed on face detection — parity FAILED")
    print(f"  WORST: blendshapes {worst_bs:.4f} (target <= 0.02), "
          f"landmarks {worst_px:.2f}px (target <= 2px on the tracked face), "
          f"head-pose {worst_deg:.2f} deg (informational)")
    return {"worst_blendshape_abs": worst_bs, "worst_landmark_px": worst_px,
            "worst_headpose_deg": worst_deg, "images": n_ok}


def run_pose_parity(pose_task, out_dir, images):
    import mediapipe as mp
    from mediapipe.tasks import python as mp_python
    from mediapipe.tasks.python import vision as mp_vision
    from PIL import Image

    ours = OnnxPosePipeline(out_dir)
    options = mp_vision.PoseLandmarkerOptions(
        base_options=mp_python.BaseOptions(model_asset_path=pose_task),
        num_poses=1)
    ref = mp_vision.PoseLandmarker.create_from_options(options)

    print("\n== POSE PARITY (ONNX pipeline vs python mediapipe) ==")
    worst_world = 0.0
    n_ok = 0
    for path in images:
        img = Image.open(path)
        mp_img = mp.Image(image_format=mp.ImageFormat.SRGB,
                          data=np.asarray(img.convert("RGB")))
        res = ref.detect(mp_img)
        mine = ours(img)
        if not res.pose_world_landmarks:
            print(f"  {os.path.basename(path)}: no pose (reference)")
            continue
        if mine is None:
            print(f"  {os.path.basename(path)}: REFERENCE found a pose, we did NOT")
            continue
        ref_world = np.array([[pt.x, pt.y, pt.z]
                              for pt in res.pose_world_landmarks[0]])
        d = np.linalg.norm(ref_world - mine["world"], axis=1)
        print(f"  {os.path.basename(path)}: world landmarks mean "
              f"{d.mean() * 100:.2f}cm max {d.max() * 100:.2f}cm "
              f"| presence {mine['presence']:.3f}")
        worst_world = max(worst_world, d.max())
        n_ok += 1
    ref.close()
    assert n_ok > 0, "no pose image produced a reference result"
    print(f"  WORST: world {worst_world * 100:.2f}cm (target <= 2cm)")
    return {"worst_world_m": worst_world, "images": n_ok}


