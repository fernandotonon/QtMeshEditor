def letterbox(img, size):
    """Keep-aspect centre letterbox to size x size (BORDER_ZERO, plain
    bilinear — cv2, NOT an antialiased resampler; matches MediaPipe's
    ImageToTensor). Returns (uint8 HxWx3 array, pad).

    pad = (pad_x, pad_y, fx, fy): normalized padding on each leading side of
    the letterboxed square and the fraction of the square the image occupies.
    """
    import cv2
    arr = np.asarray(img)
    h, w = arr.shape[:2]
    s = size / max(w, h)
    ox, oy = (size - w * s) / 2.0, (size - h * s) / 2.0
    m = np.array([[s, 0, ox], [0, s, oy]], dtype=np.float64)
    out = cv2.warpAffine(arr, m, (size, size), flags=cv2.INTER_LINEAR,
                         borderMode=cv2.BORDER_CONSTANT, borderValue=0)
    return out, (ox / size, oy / size, w * s / size, h * s / size)


def unletterbox_points(pts, pad):
    """Map normalized letterbox-square coords -> normalized original coords."""
    pad_x, pad_y, fx, fy = pad
    out = pts.copy()
    out[..., 0] = (pts[..., 0] - pad_x) / fx
    out[..., 1] = (pts[..., 1] - pad_y) / fy
    return out


def gen_ssd_anchors(input_size, strides, min_scale=0.1484375, max_scale=0.75,
                    anchor_offset=0.5, interpolated_scale_aspect_ratio=1.0):
    """MediaPipe SsdAnchorsCalculator with aspect_ratios=[1.0], fixed size."""
    def scale_for(i, n):
        if n == 1:
            return (min_scale + max_scale) * 0.5
        return min_scale + (max_scale - min_scale) * i / (n - 1)

    anchors = []
    n = len(strides)
    layer = 0
    while layer < n:
        # merge consecutive identical strides into one layer
        last = layer
        scales = []
        while last < n and strides[last] == strides[layer]:
            scales.append(scale_for(last, n))
            if interpolated_scale_aspect_ratio > 0.0:
                nxt = 1.0 if last == n - 1 else scale_for(last + 1, n)
                scales.append(math.sqrt(scales[-1] * nxt))
            last += 1
        stride = strides[layer]
        fm = int(math.ceil(input_size / stride))
        for y in range(fm):
            for x in range(fm):
                for _ in scales:
                    anchors.append(((x + anchor_offset) / fm,
                                    (y + anchor_offset) / fm))
        layer = last
    return np.array(anchors, dtype=np.float32)


def decode_detections(raw_boxes, raw_scores, anchors, input_size, num_keypoints,
                      min_score=0.5):
    """MediaPipe TensorsToDetections: fixed anchor size, no box flip."""
    scores = sigmoid(raw_scores[..., 0])
    keep = scores >= min_score
    boxes = raw_boxes[keep]
    scores = scores[keep]
    anc = anchors[keep]
    if boxes.shape[0] == 0:
        return []
    cx = boxes[:, 0] / input_size + anc[:, 0]
    cy = boxes[:, 1] / input_size + anc[:, 1]
    w = boxes[:, 2] / input_size
    h = boxes[:, 3] / input_size
    kps = np.stack([boxes[:, 4 + 2 * k:6 + 2 * k] / input_size + anc
                    for k in range(num_keypoints)], axis=1)
    dets = []
    for i in range(boxes.shape[0]):
        dets.append({
            "score": float(scores[i]),
            "box": (float(cx[i] - w[i] / 2), float(cy[i] - h[i] / 2),
                    float(w[i]), float(h[i])),
            "keypoints": kps[i].astype(float),
        })
    return weighted_nms(dets)


def weighted_nms(dets, min_suppression_threshold=0.3):
    """MediaPipe weighted non-max-suppression."""
    def iou(a, b):
        ax, ay, aw, ah = a
        bx, by, bw, bh = b
        x1, y1 = max(ax, bx), max(ay, by)
        x2, y2 = min(ax + aw, bx + bw), min(ay + ah, by + bh)
        inter = max(0.0, x2 - x1) * max(0.0, y2 - y1)
        union = aw * ah + bw * bh - inter
        return inter / union if union > 0 else 0.0

    remaining = sorted(dets, key=lambda d: -d["score"])
    out = []
    while remaining:
        best = remaining[0]
        cluster = [d for d in remaining if iou(d["box"], best["box"])
                   > min_suppression_threshold]
        remaining = [d for d in remaining if d not in cluster]
        total = sum(d["score"] for d in cluster)
        box = np.zeros(4)
        kps = np.zeros_like(np.asarray(best["keypoints"]))
        for d in cluster:
            wgt = d["score"] / total
            box += wgt * np.array(d["box"])
            kps += wgt * np.asarray(d["keypoints"])
        merged = dict(best)
        merged["box"] = tuple(box)
        merged["keypoints"] = kps
        out.append(merged)
    return out


def rect_from_face_detection(det, img_w, img_h):
    """DetectionsToRects (kp0 right eye -> kp1 left eye, target 0 deg) +
    RectTransformation(scale 1.5, square_long). rotation follows MediaPipe:
    theta = normalize(target - atan2(-(dy), dx)), y down, CCW-positive in the
    R(theta) = [[c,-s],[s,c]] image-coordinate sense."""
    x, y, w, h = det["box"]
    cx, cy = x + w / 2, y + h / 2
    kp = det["keypoints"]
    dx = (kp[1][0] - kp[0][0]) * img_w
    dy = (kp[1][1] - kp[0][1]) * img_h
    angle = normalize_angle(-math.atan2(-dy, dx))  # target angle 0
    side = max(w * img_w, h * img_h) * 1.5
    return cx * img_w, cy * img_h, side, side, angle


def rect_from_pose_detection(det, img_w, img_h):
    """AlignmentPointsRects (centre kp0, radius |kp1-kp0|, target 90 deg) +
    RectTransformation(scale 1.25, square_long). Same rotation convention as
    rect_from_face_detection."""
    kp = det["keypoints"]
    cx, cy = kp[0][0] * img_w, kp[0][1] * img_h
    dx = kp[1][0] * img_w - cx
    dy = kp[1][1] * img_h - cy
    radius = math.sqrt(dx * dx + dy * dy)
    angle = normalize_angle(math.pi / 2 - math.atan2(-dy, dx))
    side = 2 * radius * 1.25
    return cx, cy, side, side, angle


def normalize_angle(a):
    return a - 2 * math.pi * math.floor((a + math.pi) / (2 * math.pi))


def crop_rotated_rect(img, rect, out_size):
    """Sample the rotated rect (cx,cy,w,h px + MediaPipe rotation) into an
    out_size x out_size RGB uint8 array. Output (u,v) maps to image point
    centre + R(theta) . ((u/out - 0.5) * w, (v/out - 0.5) * h); plain bilinear,
    BORDER_ZERO — MediaPipe's GetRotatedSubRectToRectTransformMatrix."""
    import cv2
    arr = np.asarray(img)
    cx, cy, w, h, angle = rect
    ca, sa = math.cos(angle), math.sin(angle)
    sx, sy = w / out_size, h / out_size
    # input <- output affine, then invert for warpAffine's dst<-src semantics
    m = np.array([
        [ca * sx, -sa * sy, cx - (ca * sx + -sa * sy) * (out_size / 2.0)],
        [sa * sx, ca * sy, cy - (sa * sx + ca * sy) * (out_size / 2.0)],
    ], dtype=np.float64)
    return cv2.warpAffine(arr, m, (out_size, out_size),
                          flags=cv2.INTER_LINEAR | cv2.WARP_INVERSE_MAP,
                          borderMode=cv2.BORDER_CONSTANT, borderValue=0)


def project_landmarks(pts_norm, rect, img_w, img_h):
    """LandmarkProjection: normalized crop coords -> image pixel coords
    (x' = cx + dx*w*cos - dy*h*sin, same R(theta) as the crop)."""
    cx, cy, w, h, angle = rect
    x = pts_norm[:, 0] - 0.5
    y = pts_norm[:, 1] - 0.5
    ca, sa = math.cos(angle), math.sin(angle)
    px = cx + x * w * ca - y * h * sa
    py = cy + x * w * sa + y * h * ca
    out = pts_norm.copy()
    out[:, 0] = px
    out[:, 1] = py
    if out.shape[1] > 2:
        out[:, 2] = pts_norm[:, 2] * w
    return out


def sigmoid(x):
    x = np.clip(x, -100, 100)
    return np.where(x >= 0, 1.0 / (1.0 + np.exp(-x)),
                    np.exp(x) / (1.0 + np.exp(x)))


def umeyama_rotation(src, dst, weights):
    """Weighted Kabsch: rotation R (+ translation) with dst ~= s*R*src + t.
    Returns (R 3x3, t 3, s). Scale solved then discarded by callers that only
    want the pose."""
    w = weights / weights.sum()
    mu_s = (src * w[:, None]).sum(axis=0)
    mu_d = (dst * w[:, None]).sum(axis=0)
    sc = src - mu_s
    dc = dst - mu_d
    cov = (dc * w[:, None]).T @ sc
    U, S, Vt = np.linalg.svd(cov)
    d = np.sign(np.linalg.det(U @ Vt))
    D = np.diag([1.0, 1.0, d])
    R = U @ D @ Vt
    var = (w[:, None] * sc * sc).sum()
    s = (S * [1, 1, d]).sum() / var if var > 0 else 1.0
    t = mu_d - s * (R @ mu_s)
    return R, t, s


