class OnnxFacePipeline:
    def __init__(self, out_dir, canonical_obj, procrustes_pbtxt):
        self.det = ort_session(os.path.join(out_dir, "face", "face_detector.onnx"))
        self.lmk = ort_session(os.path.join(out_dir, "face", "face_landmarks.onnx"))
        self.bs = ort_session(os.path.join(out_dir, "face", "face_blendshapes.onnx"))
        self.det_size = self.det.get_inputs()[0].shape[1]
        self.lmk_size = self.lmk.get_inputs()[0].shape[1]
        self.anchors = gen_ssd_anchors(self.det_size, [8, 16, 16, 16])
        assert self.anchors.shape[0] == self.det.get_outputs()[0].shape[1], \
            f"anchor count {self.anchors.shape[0]} != model {self.det.get_outputs()[0].shape[1]}"
        self.canonical = load_canonical_obj(canonical_obj)
        ids, wgt = load_procrustes_basis(procrustes_pbtxt)
        self.basis_ids = ids
        self.basis_w = wgt

    def __call__(self, img):
        from PIL import Image
        img = img.convert("RGB")
        W, H = img.size
        # --- stage 1: detector
        lb, pad = letterbox(img, self.det_size)
        x = lb.astype(np.float32)[None] / 127.5 - 1.0
        raw_box, raw_score = self.det.run(None, {self.det.get_inputs()[0].name: x})
        dets = decode_detections(raw_box[0], raw_score[0], self.anchors,
                                 self.det_size, num_keypoints=6)
        if not dets:
            return None
        det = dets[0]
        det["box"] = tuple(unletterbox_points(
            np.array([[det["box"][0], det["box"][1]],
                      [det["box"][0] + det["box"][2], det["box"][1] + det["box"][3]]]),
            pad).reshape(-1))
        det["box"] = (det["box"][0], det["box"][1],
                      det["box"][2] - det["box"][0], det["box"][3] - det["box"][1])
        det["keypoints"] = unletterbox_points(np.asarray(det["keypoints"]), pad)
        rect = rect_from_face_detection(det, W, H)
        # --- stage 2: landmarks
        crop = crop_rotated_rect(img, rect, self.lmk_size)
        x = crop.astype(np.float32)[None] / 255.0
        outs = self.lmk.run(None, {self.lmk.get_inputs()[0].name: x})
        lmk_raw = outs[0].reshape(-1, 3) / self.lmk_size
        presence = float(sigmoid(outs[1].reshape(-1)[0]))
        pts = project_landmarks(lmk_raw, rect, W, H)  # px
        # --- stage 3: blendshapes (146 subset, pixel coords, 2D)
        sub = pts[BLENDSHAPE_LANDMARK_SUBSET][:, :2].astype(np.float32)
        bs = self.bs.run(None, {self.bs.get_inputs()[0].name: sub[None]})[0]
        bs = bs.reshape(-1)
        # --- head pose: weighted Kabsch canonical(cm) -> camera-ish frame
        pose_pts = np.stack([pts[:468, 0], -pts[:468, 1], -pts[:468, 2]], axis=1)
        weights = np.zeros(468, dtype=np.float64)
        weights[self.basis_ids] = self.basis_w
        R, t, s = umeyama_rotation(self.canonical, pose_pts, weights)
        return {
            "landmarks": pts,            # 478 x 3, px (z in px, w-scaled)
            "presence": presence,
            "blendshapes": bs,           # 52
            "rotation": R,               # canonical -> camera
        }


class OnnxPosePipeline:
    def __init__(self, out_dir):
        self.det = ort_session(os.path.join(out_dir, "pose", "pose_detector.onnx"))
        self.lmk = ort_session(os.path.join(out_dir, "pose", "pose_landmarks.onnx"))
        self.det_size = self.det.get_inputs()[0].shape[1]
        self.lmk_size = self.lmk.get_inputs()[0].shape[1]
        self.anchors = gen_ssd_anchors(self.det_size, [8, 16, 32, 32, 32])
        assert self.anchors.shape[0] == self.det.get_outputs()[0].shape[1]

    def __call__(self, img):
        img = img.convert("RGB")
        W, H = img.size
        lb, pad = letterbox(img, self.det_size)
        x = lb.astype(np.float32)[None] / 127.5 - 1.0
        raw_box, raw_score = self.det.run(None, {self.det.get_inputs()[0].name: x})
        dets = decode_detections(raw_box[0], raw_score[0], self.anchors,
                                 self.det_size, num_keypoints=4)
        if not dets:
            return None
        det = dets[0]
        det["keypoints"] = unletterbox_points(np.asarray(det["keypoints"]), pad)
        rect = rect_from_pose_detection(det, W, H)
        crop = crop_rotated_rect(img, rect, self.lmk_size)
        x = crop.astype(np.float32)[None] / 255.0
        outs = self.lmk.run(None, {self.lmk.get_inputs()[0].name: x})
        raw = outs[0].reshape(-1, 5)  # 39 x (x,y,z,vis,presence)
        # unlike the face model (logit), the pose flag is already a probability
        pose_flag = float(outs[1].reshape(-1)[0])
        world = outs[4].reshape(-1, 3)
        pts_norm = raw[:, :3] / self.lmk_size
        pts = project_landmarks(pts_norm, rect, W, H)
        vis = sigmoid(raw[:, 3])
        # world landmarks: rotate by the rect rotation only (no scale)
        cx, cy, w, h, angle = rect
        ca, sa = math.cos(angle), math.sin(angle)
        wx = world[:, 0] * ca - world[:, 1] * sa
        wy = world[:, 0] * sa + world[:, 1] * ca
        world_rot = np.stack([wx, wy, world[:, 2]], axis=1)
        return {
            "landmarks": pts[:33],
            "visibility": vis[:33],
            "world": world_rot[:33],
            "presence": pose_flag,
        }


def load_canonical_obj(path):
    """468 canonical face model vertices (cm), mediapipe face_geometry data."""
    verts = []
    with open(path) as f:
        for line in f:
            if line.startswith("v "):
                verts.append([float(v) for v in line.split()[1:4]])
    v = np.array(verts, dtype=np.float64)
    assert v.shape == (468, 3), v.shape
    return v


def load_procrustes_basis(path):
    ids, weights = [], []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line.startswith("procrustes_landmark_basis"):
                parts = line.replace("{", " ").replace("}", " ").split()
                ids.append(int(parts[parts.index("landmark_id:") + 1]))
                weights.append(float(parts[parts.index("weight:") + 1]))
    return np.array(ids), np.array(weights, dtype=np.float64)


