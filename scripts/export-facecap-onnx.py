#!/usr/bin/env python3
"""Convert MediaPipe Face/Pose Landmarker TFLite models to ONNX, with parity proof (#870).

ONE-TIME, OFFLINE developer tool — NOT shipped with the app, and the app never
runs Python. The app runs the resulting .onnx files in C++ via ONNX Runtime
(src/Mocap/FaceCapPredictor.cpp / PoseIK pipeline), downloading them on first
use to AppData/ai_models/mocap/{face,pose}/.

WHAT IT PRODUCES (in --out-dir, default .mocap_work/out)
  face/face_detector.onnx      BlazeFace short-range:  in [1,128,128,3] RGB in [-1,1]
                               out regressors [1,896,16], classificators [1,896,1]
  face/face_landmarks.onnx     Face Mesh V2:           in [N,256,256,3] RGB in [0,1]
                               out [N,1,1,1434] (478 xyz landmarks, px in 256-space),
                                   [N,1,1,1] face-presence logit, [N,1] (unused aux)
  face/face_blendshapes.onnx   MLP-Mixer blendshapes:  in [1,146,2] (x*W, y*H pixel coords
                               of the 146-landmark subset), out [52] scores in [0,1]
  pose/pose_detector.onnx      BlazePose detector:     in [1,224,224,3] RGB in [-1,1]
                               out [1,2254,12], [1,2254,1]
  pose/pose_landmarks.onnx     BlazePose full:         in [1,256,256,3] RGB in [0,1]
                               out [1,195] (39 x,y,z,visibility,presence in 256-space),
                                   [1,1] pose-presence, [1,256,256,1] seg, [1,64,64,39] heatmap,
                                   [1,117] world landmarks (39 xyz, metres, hip-centred)

DATA + LICENSE
  All five models are Google MediaPipe models, Apache-2.0 (code AND weights) —
  see THIRD_PARTY_AI_MODELS.md. Downloaded .task bundles are zip files
  containing the TFLite graphs this script converts.

CONVERSION NOTES (discovered empirically, kept for reproducibility)
  * tf2onnx 1.17.0 + tensorflow 2.21 + python 3.12 work.
  * pose_detector.tflite ships fp16 block-SPARSE weights behind DENSIFY ops,
    which tf2onnx cannot parse. densify_tflite() runs the TFLite interpreter
    with experimental_preserve_all_tensors, captures each DENSIFY output, and
    rewrites the flatbuffer with dense buffers + the DENSIFY ops removed.
  * face_blendshapes.tflite converts, but tf2onnx's post-conversion optimizer
    produces a graph onnxruntime rejects (transpose optimizer breaks a
    LayerNorm Mul). We convert that model with optimizers DISABLED.

PRE/POST-PROCESSING CONTRACT (the spec Slice C implements in C++; also in
docs/MOCAP_SPIKE.md):
  * Detector input: letterbox (keep aspect, centre, pad both sides) to the
    input size, RGB, normalize to [-1,1] ((v/255)*2-1).
  * Face SSD anchors: 4 layers, strides [8,16,16,16], 2 anchors on the two
    16x16 layers' merged... generated by gen_ssd_anchors() below (896 anchors,
    all 1.0 aspect, fixed size). Pose: 5 layers, strides [8,16,32,32,32]
    (2254 anchors). Decode: offsets / input_size scaled around anchor centres;
    score = sigmoid(clip(raw, -100, 100)); weighted NMS at IoU 0.3.
  * Face ROI: rotation from detector keypoint 0 (right eye) -> 1 (left eye),
    target angle 0; rect = detection box made square-long then scaled 1.5x.
  * Pose ROI: centre = detector keypoint 0 (mid-hip), radius = |kp1-kp0|,
    box = 2*radius square, rotation target angle 90 deg, then scaled 1.25x.
  * Landmark crop: rotated rect resampled to 256x256, RGB in [0,1].
  * Landmark decode: xyz / 256 -> normalized crop coords -> rotate/scale back
    through the ROI transform (landmark projection); z scaled by rect w.
  * Blendshape input: the 146-subset landmark (x*imgW, y*imgH) pixel coords.
  * Pose world landmarks: rotate x,y by the ROI rotation only (no scale).
  * Head pose: weighted Umeyama/Kabsch fit of the 468 canonical-face-model
    vertices (Procrustes basis weights) against screen landmarks
    (x*W, -y*H, -z*W); rotation kept, scale discarded. This intentionally
    replaces MediaPipe's perspective geometry pipeline; parity vs its
    facial_transformation_matrix is reported in degrees (a few deg is fine).

USAGE (offline, in a venv with mediapipe tensorflow tf2onnx onnx onnxruntime pillow):
    python scripts/export-facecap-onnx.py \
        --face-task .mocap_work/models/face_landmarker.task \
        --pose-task .mocap_work/models/pose_landmarker_full.task \
        --images .mocap_work/images --out-dir .mocap_work/out
"""

