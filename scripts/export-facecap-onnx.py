def densify_tflite(src, dst):
    """Rewrite a TFLite flatbuffer with all DENSIFY'd sparse constants dense.

    tf2onnx cannot parse TFLite block-sparse tensors. The TFLite interpreter
    can (XNNPACK densifies at prepare time), so we run it once with
    experimental_preserve_all_tensors, read back each DENSIFY output, store it
    as a dense buffer on the op's input tensor, rewire consumers and drop the
    DENSIFY ops. Returns the number of ops removed (0 = no rewrite needed).
    """
    import tensorflow as tf
    from tensorflow.lite.tools import flatbuffer_utils
    from tensorflow.lite.python import schema_py_generated as schema

    names = {v: k for k, v in schema.BuiltinOperator.__dict__.items()
             if isinstance(v, int)}
    model = flatbuffer_utils.read_model(src)
    sg = model.subgraphs[0]

    def is_densify(op):
        code = model.operatorCodes[op.opcodeIndex]
        bc = max(code.builtinCode, getattr(code, "deprecatedBuiltinCode", 0))
        return names.get(bc) == "DENSIFY"

    if not any(is_densify(op) for op in sg.operators):
        shutil.copyfile(src, dst)
        return 0

    interp = tf.lite.Interpreter(
        model_path=src,
        experimental_preserve_all_tensors=True,
        # XNNPACK folds DENSIFY away and get_tensor() then reads garbage —
        # run pure-builtin so every intermediate tensor is materialized.
        experimental_op_resolver_type=tf.lite.experimental.OpResolverType
        .BUILTIN_WITHOUT_DEFAULT_DELEGATES)
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    interp.set_tensor(inp["index"], np.zeros(inp["shape"], dtype=inp["dtype"]))
    interp.invoke()

    kept = []
    removed = 0
    for op in sg.operators:
        if not is_densify(op):
            kept.append(op)
            continue
        removed += 1
        ti, to = int(op.inputs[0]), int(op.outputs[0])
        dense = interp.get_tensor(to)
        tensor = sg.tensors[ti]
        # type 1 == FLOAT16 in the tflite schema; keep the storage dtype.
        data = np.ascontiguousarray(
            dense.astype(np.float16 if tensor.type == 1 else dense.dtype)
        ).tobytes()
        buf = schema.BufferT()
        buf.data = np.frombuffer(data, dtype=np.uint8)
        model.buffers.append(buf)
        tensor.buffer = len(model.buffers) - 1
        tensor.sparsity = None
        for other in sg.operators:
            if other is not op:
                other.inputs = [ti if int(x) == to else int(x)
                                for x in other.inputs]
    sg.operators = kept
    flatbuffer_utils.write_model(model, dst)
    return removed


def convert_tflite_to_onnx(tflite_path, onnx_path, optimize=True):
    """tf2onnx conversion via the python API so the optimizer can be skipped."""
    import onnx
    from tf2onnx.tfonnx import process_tf_graph
    from tf2onnx import optimizer as tf2onnx_optimizer

    g = process_tf_graph(None, opset=18, tflite_path=tflite_path)
    if optimize:
        g = tf2onnx_optimizer.optimize_graph(g, catch_errors=True)
    model_proto = g.make_model(os.path.basename(onnx_path))
    onnx.save(model_proto, onnx_path)


def ort_session(path):
    import onnxruntime as ort
    return ort.InferenceSession(path, providers=["CPUExecutionProvider"])


def convert_with_fallback(tflite_path, onnx_path):
    """Convert; if onnxruntime rejects the optimized graph, retry unoptimized."""
    work = tflite_path
    dense = onnx_path + ".dense.tflite"
    removed = densify_tflite(tflite_path, dense)
    if removed:
        print(f"    densified {removed} sparse tensors")
        work = dense
    try:
        convert_tflite_to_onnx(work, onnx_path, optimize=True)
        ort_session(onnx_path)
        mode = "optimized"
    except Exception as exc:  # noqa: BLE001 - any ORT load failure
        print(f"    optimized graph rejected ({type(exc).__name__}); "
              "retrying with tf2onnx optimizers disabled")
        convert_tflite_to_onnx(work, onnx_path, optimize=False)
        ort_session(onnx_path)
        mode = "unoptimized"
    if os.path.exists(dense):
        os.remove(dense)
    print(f"    -> {onnx_path} ({mode}, "
          f"{os.path.getsize(onnx_path) / 1e6:.1f} MB)")


